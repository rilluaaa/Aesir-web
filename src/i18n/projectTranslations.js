export const localizeProject = (project, language) => {
  if (language === "en") {
    return { ...project, originalTitle: project.title, originalCategory: project.category };
  }

  return {
    ...project,
    originalTitle: project.title,
    originalCategory: project.category,
    title: PROJECT_TITLE_TRANSLATIONS[language]?.[project.title] ?? project.title,
    category: PROJECT_CATEGORY_TRANSLATIONS[language]?.[project.category] ?? project.category,
    description: PROJECT_DESCRIPTION_TRANSLATIONS[language]?.[project.title] ?? project.description,
  };
};
